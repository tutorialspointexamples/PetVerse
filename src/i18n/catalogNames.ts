function translateToken(locale: LocaleId, token: string): string {
  if (locale === 'en') return token
  const map = WORDS[locale]
  const lower = token.toLowerCase()
  const hit = map[lower]
  if (!hit) return token
  // Preserve simple Title Case when the source token was capitalized
  if (token[0] === token[0]?.toUpperCase()) {
    return hit
  }
  return hit
}

/** Localize a catalog display name by translating known English words. */
export function localizeCatalogName(name: string, locale: LocaleId): string {
  if (locale === 'en' || !name) return name
  return name
    .split(/(\s+|-)/)
    .map((part) => {
      if (!part || part === ' ' || part === '-' || /^\s+$/.test(part)) return part
      // Keep short connectors / numbers
      if (/^\d/.test(part) || part.length <= 1) return part
      return translateToken(locale, part)
    })
    .join('')
}
